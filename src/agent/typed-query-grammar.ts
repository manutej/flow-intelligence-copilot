import { DATE_WINDOWS } from '../config/rules.ts';
import type { PortfolioStore } from '../data/schema.ts';
import { ACCEPTED, AGGREGATION_SET, BOUNDS, DIRECTIONS, DOMAIN_SET, LEASE_TYPES, MEASURES, RENEWAL, STATUSES, TOPK } from './typed-query.ts';

/**
 * The llama.cpp GBNF for a model reply, generated from the same closed sets
 * and bounds typedQueryErrors checks, so the grammar never admits a value
 * the validator rejects. What a grammar cannot say (a lower bound above its
 * upper bound) stays with the validator, and an invalid reply falls back to
 * the model-off result. grammar/flowiq-typedquery.gbnf is this output;
 * `node scripts/gen-grammar.ts` rewrites it and a test fails on drift.
 */
export function typedQueryGrammar(store: PortfolioStore): string {
  const lit = (v: string) => JSON.stringify(JSON.stringify(v));
  const alt = (vs: Iterable<string>) => [...vs].map(lit).join(' | ');
  const sorted = (vs: Iterable<string>) => [...new Set(vs)].filter(Boolean).sort();
  const statuses = sorted(STATUSES);
  const pairs = statuses.flatMap((a, i) => statuses.slice(i + 1).map((b) => `"[${lit(a).slice(1, -1)},${lit(b).slice(1, -1)}]"`));
  const bound = (k: string) => BOUNDS.find(([lo]) => lo === k)!;
  const uintUpTo = (max: number) => `"0" | [1-9] [0-9]{0,${String(Math.floor(max)).length - 1}}`;
  const staticWindows = Object.keys(DATE_WINDOWS).filter((k) => !/^[A-Z]{3}_20\d\d$|^YEAR_20\d\d$/.test(k));
  const filters: Array<[string, string]> = [
    ['topK', 'topk'], ['buildingClass', 'building-class'], ['yearBuiltMin', 'year'], ['yearBuiltMax', 'year'],
    ['bedrooms', 'count'], ['bathrooms', 'half-num'], ['rentMin', 'rent'], ['rentMax', 'rent'],
    ['bedroomsMin', 'count'], ['bedroomsMax', 'count'], ['bathroomsMin', 'half-num'], ['bathroomsMax', 'half-num'],
    ['sqftMin', 'sqft'], ['sqftMax', 'sqft'], ['floorMin', 'floor'], ['floorMax', 'floor'], ['view', 'view'],
  ];
  const tail: Array<[string, string]> = [
    ['leaseType', 'lease-type'], ['renewalStatus', 'renewal-status'], ['leaseStartWindow', 'date-window'],
    ['leaseEndWindow', 'date-window'], ['decisionAccepted', 'decision-accepted'], ['decisionDirection', 'decision-direction'],
  ];
  const key = (k: string) => JSON.stringify(`,"${k}":`);
  const opt = ([k, rule]: [string, string]) => `( ${key(k)} ${rule} )?`;
  const [, , ybMin, ybMax] = bound('yearBuiltMin');
  const centuries = Array.from({ length: Math.floor(ybMax / 100) - Math.floor(ybMin / 100) + 1 }, (_, i) => `"${Math.floor(ybMin / 100) + i}"`).join(' | ');
  return `# FlowIQ model reply: TypedQuery | Clarify | DraftRequest -- llama.cpp GBNF
# GENERATED by src/agent/typed-query-grammar.ts from the closed sets in
# src/agent/typed-query.ts, DATE_WINDOWS and the store. Do not edit by hand.
# Clarify and draft are replies the model may give; FlowIQ then answers on the
# deterministic path, as with the model off.

root ::= typed-query | clarify | draft

typed-query ::= "{\\"kind\\":\\"query\\",\\"question\\":" string ",\\"intent\\":" intent "}"

intent ::= "{\\"domain\\":" domain ",\\"measure\\":" measure ",\\"aggregation\\":" aggregation ",\\"isWholePortfolioExplicit\\":" bool ",\\"isClassComparison\\":" bool ",\\"dateWindow\\":" date-window ",\\"dateExplicit\\":" bool ",\\"mentionedSources\\":" sources ",\\"paidOnly\\":" bool ",\\"decisionIds\\":" decision-ids
  ${filters.map(opt).join('\n  ')}
  ( ${key('unitStatus')} unit-status | ${key('unitStatusIn')} unit-status-pair )?
  ${tail.map(opt).join('\n  ')}
  "}"

domain ::= ${alt(DOMAIN_SET)}
measure ::= ${alt(MEASURES)}
aggregation ::= ${alt(AGGREGATION_SET)}
unit-status ::= ${alt(statuses)}
unit-status-pair ::= ${pairs.join(' | ')}
lease-type ::= ${alt(LEASE_TYPES)}
renewal-status ::= ${alt(RENEWAL)}
decision-accepted ::= ${alt(ACCEPTED)}
decision-direction ::= ${alt(DIRECTIONS)}
building-class ::= ${alt(sorted(store.properties.map((p) => p.buildingClass)))}
view ::= ${alt(sorted(store.units.map((u) => u.view.trim())))}
sources ::= "[]" | "[" source ( "," source )* "]"
source ::= ${alt(sorted([...store.paidSources, ...store.organicSources]))}
decision-ids ::= "[]" | "[" decision-id ( "," decision-id )* "]"
decision-id ::= ${alt(sorted(store.decisions.map((d) => d.decisionId)))}
date-window ::= "\\"" ( ${staticWindows.map((k) => `"${k}"`).join(' | ')} | mon "_20" [0-9] [0-9] | "YEAR_20" [0-9] [0-9] ) "\\""
mon ::= "JAN" | "FEB" | "MAR" | "APR" | "MAY" | "JUN" | "JUL" | "AUG" | "SEP" | "OCT" | "NOV" | "DEC"

clarify ::= "{\\"kind\\":\\"clarify\\",\\"options\\":[" string "," string ( "," string )? ( "," string )? "]}"
draft ::= "{\\"kind\\":\\"draft\\",\\"request\\":" string "}"

bool ::= "true" | "false"
topk ::= ${Array.from({ length: TOPK[1] - TOPK[0] + 1 }, (_, i) => `"${TOPK[0] + i}"`).join(' | ')}
count ::= [0-9]
half-num ::= [0-9] ( ".5" )?
year ::= ( ${centuries} ) [0-9] [0-9]
sqft ::= ${uintUpTo(bound('sqftMin')[3])}
floor ::= ${uintUpTo(bound('floorMin')[3])}
rent ::= ${uintUpTo(bound('rentMin')[3])}
string ::= "\\"" char{1,300} "\\""
char ::= [^"\\\\\\x00-\\x1f] | "\\\\" ( ["\\\\/bfnrt] | "u" [0-9a-fA-F]{4} )
`;
}
